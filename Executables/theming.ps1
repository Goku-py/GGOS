# GGOS theming (v0.5.0, feature-expansion track) - option ggos-theme.
# Applies the shipped GGOS wallpaper:
#   1. Copies Executables\Assets\ggos-wallpaper.jpg to
#      %SystemRoot%\GGOS\Assets\ggos-wallpaper.jpg (creates the directory).
#      The staged copy under %SystemRoot% is the durable file every hive's
#      WallPaper value points at; the package source is not guaranteed to
#      survive the wizard run.
#   2. Writes HKCU\Control Panel\Desktop WallPaper (REG_SZ = staged path) via
#      the shared per-user engine Apply-GGUserValues (ggos-common.psm1) - the
#      exact per-user.ps1 sweep pattern: every loaded interactive hive
#      (S-1-5-21-* SIDs with the 'Volatile Environment' marker), HKU\.DEFAULT
#      and the Default profile template, each hive exported to
#      %SystemRoot%\GGOS\hive-backups\ before the write. Control
#      Panel\Desktop!WallPaper is the persisted form of the wallpaper setting
#      that SystemParametersInfo(SPI_SETDESKWALLPAPER) maintains
#      (Microsoft Learn, SystemParametersInfo function:
#      https://learn.microsoft.com/en-us/windows/win32/api/winuser/nf-winuser-systemparametersinfo).
#   3. Applies the wallpaper live for the wizard's session via
#      SystemParametersInfo(SPI_SETDESKWALLPAPER = 0x0014,
#      SPIF_UPDATEINIFILE | SPIF_SENDWININICHANGE = 0x03) through an
#      Add-Type P/Invoke (user32.dll, same Learn source). The registry sweep
#      above covers later logons even when the live call has no effect in the
#      elevated context.
# If the shipped asset is missing, the skip is appended to
# %SystemRoot%\GGOS\skipped.txt and the script exits 0 (the asset is
# generated by a separate track; the path is wired regardless - a build
# without it must not fail the run).
# Revert honesty: the user's previous wallpaper value is NOT recorded, so
# this option is documented as not revertable in Tasks/revert.yml.
# All external calls go through Invoke-GGCommand (spec B2 bounded timeout;
# timeouts are appended to %SystemRoot%\GGOS\skipped.txt by the wrapper).

param()

$ErrorActionPreference = 'Continue'
Import-Module (Join-Path $PSScriptRoot 'ggos-common.psm1') -Force

$reg = Join-Path $env:SystemRoot 'System32\reg.exe'
$dataDir = Join-Path $env:SystemRoot 'GGOS'
$skippedFile = Join-Path $dataDir 'skipped.txt'

$srcAsset = Join-Path $PSScriptRoot 'Assets\ggos-wallpaper.jpg'
$destDir = Join-Path $dataDir 'Assets'
$destAsset = Join-Path $destDir 'ggos-wallpaper.jpg'

# ---------------------------------------------------------------------------
# 1. Stage the wallpaper asset (skip gracefully when not shipped)
# ---------------------------------------------------------------------------
if (-not (Test-Path -LiteralPath $srcAsset)) {
    # The wallpaper is generated by a separate track; a build that does not
    # ship it must still complete the run (nothing else depends on it).
    try {
        New-Item -ItemType Directory -Path $dataDir -Force -ErrorAction Stop | Out-Null
        Add-Content -Path $skippedFile -ErrorAction Stop `
            -Value ('{0} SKIPPED(asset missing): {1}' -f (Get-Date -Format s), $srcAsset)
    }
    catch {
        Write-GGLog ('Warning: could not append to skipped.txt: ' + $_.Exception.Message)
    }
    Write-GGLog 'Wallpaper asset not found - theming skipped (see skipped.txt).'
    exit 0
}

try {
    New-Item -ItemType Directory -Path $destDir -Force -ErrorAction Stop | Out-Null
    Copy-Item -LiteralPath $srcAsset -Destination $destAsset -Force -ErrorAction Stop
    Write-GGLog ('Wallpaper staged to ' + $destAsset)
}
catch {
    Write-GGLog ('Warning: could not stage the wallpaper: ' + $_.Exception.Message)
    exit 0
}

# ---------------------------------------------------------------------------
# 2. Per-user WallPaper value through the shared triple sweep
# ---------------------------------------------------------------------------
$ThemeValues = @(
    @{ Op = 'set'; Path = 'Control Panel\Desktop'; Name = 'WallPaper'; Type = 'String'; Data = $destAsset; Group = 'core' }
)

$result = Apply-GGUserValues -ValueTable $ThemeValues -Groups @('core') -DefaultGroups @('core')
Write-GGLog ('Wallpaper registry sweep: hives processed ' + $result.HivesTouched + '; values applied ' + $result.Applied + '; failures ' + $result.Failures + '.')

# ---------------------------------------------------------------------------
# 3. Live apply for the wizard's session (SPI_SETDESKWALLPAPER)
# ---------------------------------------------------------------------------
try {
    if (-not ('GGWallpaperApi' -as [type])) {
        Add-Type -TypeDefinition @"
using System;
using System.Runtime.InteropServices;
public static class GGWallpaperApi
{
    [DllImport("user32.dll", CharSet = CharSet.Unicode, SetLastError = true)]
    public static extern int SystemParametersInfo(uint uiAction, uint uiParam, string pvParam, uint fWinIni);
}
"@ -ErrorAction Stop
    }
    # SPI_SETDESKWALLPAPER = 0x0014; SPIF_UPDATEINIFILE | SPIF_SENDWININICHANGE = 0x03
    # (nonzero return = success; documented at the Learn URL in the header).
    $spi = [GGWallpaperApi]::SystemParametersInfo(0x0014, 0, $destAsset, 0x03)
    if ($spi -ne 0) { Write-GGLog 'Wallpaper applied live via SystemParametersInfo (SPI_SETDESKWALLPAPER).' }
    else { Write-GGLog 'Warning: live wallpaper apply returned failure (registry values are still set for the next logon).' }
}
catch {
    Write-GGLog ('Warning: live wallpaper apply could not run: ' + $_.Exception.Message)
}

# ---------------------------------------------------------------------------
# 4. Run stamp: HKLM\SOFTWARE\GGOS Theme = applied
# ---------------------------------------------------------------------------
$ok, $exit, $out = Invoke-GGCommand -FilePath $reg -ArgumentList @('add', 'HKLM\SOFTWARE\GGOS', '/v', 'Theme', '/t', 'REG_SZ', '/d', 'applied', '/f') -TimeoutSeconds 20 -Description 'HKLM\SOFTWARE\GGOS Theme stamp'
if (Test-GGRegSuccess $ok $exit $out) {
    Write-GGLog 'HKLM\SOFTWARE\GGOS stamped: Theme = applied.'
}
else {
    Write-GGLog 'Warning: the HKLM\SOFTWARE\GGOS Theme stamp could not be written.'
}

exit 0
